import type { CostcoReceipt, CostcoPriceCheck } from "./vault-types.ts";
import { COSTCO_REWARD_RATE, COSTCO_REWARD_CAP } from "./costco-reward.ts";

// The one real source for both the Executive 2% Reward calculation and the Price Match
// Watchlist -- built from ACTUAL itemized Costco receipts (tools/costco-receipts/), not guessed
// from Day Book voucher narration the way lib/costco-reward.ts's older estimate still is.
// Narration can only ever approximate ("probably a qualifying Costco purchase, probably not a
// Shop Card") -- a real receipt's own fields settle both questions exactly: `receiptType` says
// Gas Station outright (no regex needed), and a Shop Card purchase/reload shows up as its own
// distinct item line (no guessing from a vague "no dollar figure given" narration).

const GAS_RECEIPT_RE = /gas/i;
// Matches a Shop Card line ITEM the same way lib/costco-reward.ts's narration-based
// costcoQualifyingAmount matches a Shop Card VOUCHER -- only Costco's own Shop Card, never a
// third-party gift card (Uber, Southwest, etc.), which is itself a qualifying purchase.
const SHOP_CARD_ITEM_RE = /shop\s*card/i;

export function isQualifyingReceipt(r: CostcoReceipt): boolean {
  return !GAS_RECEIPT_RE.test(r.receiptType || "");
}

export function isQualifyingReceiptItem(description: string): boolean {
  return !SHOP_CARD_ITEM_RE.test(description);
}

// Merges a freshly-uploaded batch into whatever receipts are already on file, deduped by `key`
// (see CostcoReceipt's own comment -- warehouse+register+transaction number+date, generated by
// tools/costco-receipts/parse.mjs). The incoming copy wins on a key collision: a later capture
// run clicking into a receipt's full detail is strictly more complete than an earlier one that
// only saw the list-view summary, and re-uploading the exact same file is a no-op either way.
export function mergeCostcoReceipts(existing: CostcoReceipt[], incoming: CostcoReceipt[]): CostcoReceipt[] {
  const byKey = new Map(existing.map((r) => [r.key, r]));
  for (const r of incoming) byKey.set(r.key, r);
  return [...byKey.values()].sort((a, b) => (a.date < b.date ? 1 : -1));
}

// Parses/validates an uploaded receipts.json -- deliberately permissive about EXTRA fields (so a
// future parse.mjs can add more without breaking older uploads) but strict about the handful of
// fields actually used, since a malformed upload silently corrupting the reward/watchlist
// calculation would be far worse than just rejecting it with a clear error.
export function parseCostcoReceiptsUpload(raw: unknown): CostcoReceipt[] {
  if (!Array.isArray(raw)) throw new Error("Expected a JSON array of receipts (from receipts.json).");
  return raw.map((r, i) => {
    if (typeof r !== "object" || r === null) throw new Error(`Receipt ${i}: not an object.`);
    const o = r as Record<string, unknown>;
    if (typeof o.key !== "string" || !o.key) throw new Error(`Receipt ${i}: missing "key".`);
    if (typeof o.date !== "string" || !/^\d{4}-\d{2}-\d{2}$/.test(o.date)) throw new Error(`Receipt ${i} (${o.key}): bad or missing "date".`);
    if (!Array.isArray(o.items)) throw new Error(`Receipt ${i} (${o.key}): missing "items" array.`);
    return {
      key: o.key,
      cardholder: typeof o.cardholder === "string" ? o.cardholder : "",
      date: o.date,
      warehouse: typeof o.warehouse === "string" ? o.warehouse : "",
      receiptType: typeof o.receiptType === "string" ? o.receiptType : "",
      total: typeof o.total === "number" ? o.total : 0,
      items: (o.items as unknown[]).map((item, j) => {
        if (typeof item !== "object" || item === null) throw new Error(`Receipt ${i} (${o.key}), item ${j}: not an object.`);
        const it = item as Record<string, unknown>;
        return {
          itemNumber: typeof it.itemNumber === "string" ? it.itemNumber : "",
          description: typeof it.description === "string" ? it.description : "",
          amount: typeof it.amount === "number" ? it.amount : 0,
          qty: typeof it.qty === "number" ? it.qty : 1,
        };
      }),
    };
  });
}

// Merges a freshly-uploaded price-checks.json batch, deduped by itemNumber -- the incoming
// (presumably newer) check wins on a collision, since prices change and a re-run should always
// supersede a stale one.
export function mergeCostcoPriceChecks(existing: CostcoPriceCheck[], incoming: CostcoPriceCheck[]): CostcoPriceCheck[] {
  const byItem = new Map(existing.map((c) => [c.itemNumber, c]));
  for (const c of incoming) byItem.set(c.itemNumber, c);
  return [...byItem.values()].sort((a, b) => (a.checkedAt < b.checkedAt ? 1 : -1));
}

export function parseCostcoPriceChecksUpload(raw: unknown): CostcoPriceCheck[] {
  if (!Array.isArray(raw)) throw new Error("Expected a JSON array of price checks (from price-checks.json).");
  return raw.map((r, i) => {
    if (typeof r !== "object" || r === null) throw new Error(`Price check ${i}: not an object.`);
    const o = r as Record<string, unknown>;
    if (typeof o.itemNumber !== "string" || !o.itemNumber) throw new Error(`Price check ${i}: missing "itemNumber".`);
    return {
      itemNumber: o.itemNumber,
      description: typeof o.description === "string" ? o.description : "",
      pricePaid: typeof o.pricePaid === "number" ? o.pricePaid : 0,
      currentPrice: typeof o.currentPrice === "number" ? o.currentPrice : null,
      priceSource: o.priceSource === "warehouse" || o.priceSource === "online" ? o.priceSource : null,
      currentPriceWarehouse: typeof o.currentPriceWarehouse === "string" ? o.currentPriceWarehouse : null,
      notSoldOnline: o.notSoldOnline === true,
      priceDropped: o.priceDropped === true,
      checkedAt: typeof o.checkedAt === "string" ? o.checkedAt : new Date().toISOString(),
    };
  });
}

export type CostcoReceiptRewardEstimate = {
  qualifyingSpend: number;
  estimatedReward: number;
  capped: boolean;
  receiptCount: number;
};

// Same formula lib/costco-reward.ts's computeCostcoRewardEstimate uses (2% capped at $1,250),
// but summed from real item-level data instead of a whole-voucher narration guess -- a mixed
// receipt (regular items + a Shop Card reload in the same trip) is handled exactly, not by the
// narration version's "whole voucher in or out" approximation.
export function computeCostcoRewardFromReceipts(receipts: CostcoReceipt[], windowStart: string, windowEnd: string): CostcoReceiptRewardEstimate {
  let qualifyingSpend = 0;
  let receiptCount = 0;
  for (const r of receipts) {
    if (r.date < windowStart || r.date >= windowEnd) continue;
    if (!isQualifyingReceipt(r)) continue;
    let used = false;
    for (const item of r.items) {
      if (!isQualifyingReceiptItem(item.description)) continue;
      qualifyingSpend += item.amount;
      used = true;
    }
    if (used) receiptCount++;
  }
  const rawReward = Math.max(0, qualifyingSpend) * COSTCO_REWARD_RATE;
  return { qualifyingSpend, estimatedReward: Math.min(rawReward, COSTCO_REWARD_CAP), capped: rawReward > COSTCO_REWARD_CAP, receiptCount };
}

export type CostcoWatchlistItem = {
  cardholder: string;
  date: string;
  warehouse: string;
  itemNumber: string;
  description: string;
  pricePaid: number;
  qty: number;
  priceAdjustmentDeadlineAtLeast: string;
  daysLeft: number;
};

// Costco's price-adjustment window is 30 days on most items, but longer (90 days is common) on
// certain categories, electronics among them -- there is no reliable field in this data to tell
// "this is a TV" apart from anything else, so this always uses the conservative 30-day floor and
// callers should treat it as "AT LEAST this long", not an exact cutoff. Gas and Shop Card lines
// are excluded the same way the reward calculation excludes them -- neither is something you'd
// ever price-match.
const PRICE_ADJUSTMENT_WINDOW_DAYS = 30;

export function costcoPriceMatchWatchlist(receipts: CostcoReceipt[], asOfDate: string, windowDays = PRICE_ADJUSTMENT_WINDOW_DAYS): CostcoWatchlistItem[] {
  const out: CostcoWatchlistItem[] = [];
  for (const r of receipts) {
    if (!isQualifyingReceipt(r)) continue;
    const deadline = addDaysIso(r.date, windowDays);
    if (asOfDate > deadline) continue;
    const daysLeft = Math.round((new Date(deadline).getTime() - new Date(asOfDate).getTime()) / 86400000);
    for (const item of r.items) {
      if (!isQualifyingReceiptItem(item.description)) continue;
      out.push({
        cardholder: r.cardholder,
        date: r.date,
        warehouse: r.warehouse,
        itemNumber: item.itemNumber,
        description: item.description,
        pricePaid: item.amount,
        qty: item.qty,
        priceAdjustmentDeadlineAtLeast: deadline,
        daysLeft,
      });
    }
  }
  return out.sort((a, b) => (a.date < b.date ? 1 : -1));
}

function addDaysIso(dateIso: string, days: number): string {
  const d = new Date(dateIso + "T00:00:00Z");
  d.setUTCDate(d.getUTCDate() + days);
  return d.toISOString().slice(0, 10);
}
